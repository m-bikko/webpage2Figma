/** Бандл в виде ТЕКСТА — для передачи через буфер обмена.
 *
 *  Смысл ровно один: убрать из пути «скачать файл, найти в загрузках,
 *  выбрать в плагине» два шага, которые к делу не относятся. Формат
 *  внутри тот же самый ZIP; меняется только упаковка на время
 *  переноса.
 *
 *  Разбор живёт ЗДЕСЬ, а не в окне плагина, хотя вставляют именно
 *  туда. Окно — это отдельный HTML без сборки, и декодер в нём стал бы
 *  вторым экземпляром той же логики. Второй экземпляр рано или поздно
 *  расходится с первым молча: ровно так в этом проекте уже разошлись
 *  вшитый в расширение сериализатор и его исходник. Окно поэтому
 *  остаётся глупым и просто передаёт строку дальше. */

/** Маркер с номером версии формата ПЕРЕНОСА, а не бандла.
 *
 *  Нужен, чтобы отличить нашу строку от любой другой: в буфере у
 *  человека чаще всего лежит что угодно ещё, и «вставил не то» обязано
 *  читаться как понятный отказ, а не как «файл повреждён».
 *
 *  Версия отдельная от `IR_VERSION` намеренно: она про обёртку.
 *  Совместимость содержимого проверяет распаковщик, и делать это
 *  дважды в двух местах значило бы разрешить им разойтись. */
const MARKER = 'w2f1:'

/** Куски по 32768 намеренно: `String.fromCharCode(...массив)`
 *  раскладывает массив в аргументы, а на длине в сотни тысяч это
 *  переполняет стек вызовов. Отказ при этом выглядит как
 *  «Maximum call stack size exceeded» — сообщение, по которому
 *  причину не найти. */
const CHUNK = 0x8000

export const encodeBundleText = (zip: Uint8Array): string => {
  let binary = ''
  for (let i = 0; i < zip.length; i += CHUNK) {
    binary += String.fromCharCode(...zip.subarray(i, i + CHUNK))
  }
  return MARKER + btoa(binary)
}

/** Разбирает вставленное. Бросает с текстом, который человеку говорит,
 *  что делать, — а не «неверный формат».
 *
 *  Пустой результат НЕ возвращается: пустой бандл неотличим от
 *  «ничего не произошло», и окно плагина застыло бы молча. Именно так
 *  выглядел первый отказ у пользователя, и с тех пор это правило. */
export const decodeBundleText = (text: string): Uint8Array => {
  /** Пробелы по краям снимаются: буфер приносит их постоянно — из
   *  редактора, из чата, из письма. Требовать от человека чистой
   *  строки значило бы отказывать по причине, которой он не видит. */
  const trimmed = text.trim()
  if (trimmed.length === 0) {
    throw new Error('Поле пустое: нечего вставлять.')
  }
  if (!trimmed.startsWith(MARKER)) {
    const head = trimmed.slice(0, 24)
    throw new Error(
      `Это не бандл webpage2figma: строка обязана начинаться с "${MARKER}", ` +
      `а начинается с "${head}${trimmed.length > 24 ? '…' : ''}". ` +
      `Нажми «Скопировать для Figma» в расширении и вставь снова.`,
    )
  }

  const payload = trimmed.slice(MARKER.length)
  /** Перенос строки внутри полезной части — не порча, а след почты
   *  или мессенджера. Base64 переносов не содержит, поэтому их
   *  снятие однозначно и ничего не прячет. */
  const cleaned = payload.replace(/\s+/g, '')

  let binary: string
  try {
    binary = atob(cleaned)
  } catch {
    /** Чаще всего это обрезанная строка: буфер отдал не всё, или
     *  вставку оборвали. Сказать «строка повреждена» мало — человеку
     *  нужно знать, что делать. */
    throw new Error(
      'Строка повреждена или скопирована не целиком: base64 не ' +
      'разбирается. Скопируй заново — выделять вручную не нужно, ' +
      'кнопка кладёт в буфер всё сразу.',
    )
  }

  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i)
  if (bytes.length === 0) {
    throw new Error('После маркера ничего нет: скопировано пустое значение.')
  }
  return bytes
}
