/** Версия формата IR. Обе половины системы сверяют её и отказываются
 *  работать при несовпадении — молчаливая деградация запрещена.
 *
 *  2: `rect` стал координатами родителя вместо абсолютных. Смена версии
 *  здесь обязательна и не косметическая: тип поля не изменился, поэтому
 *  бандл прошлой редакции пройдёт проверку схемы целиком и будет
 *  построен неверно — каждый вложенный узел уедет на смещение родителя.
 *  Версия — единственное, что эти редакции различает.
 *
 *  3: `selfLayout` получил `margin` и `marginAuto`, а `LayoutMode` —
 *  член `grid`. Схема и сама отвергнет бандл прошлой редакции: поля
 *  обязательные. Но сообщение «поле margin обязательно» ничего не
 *  говорит человеку, у которого на диске лежит файл недельной
 *  давности, а «бандл версии 2, читатель понимает 3» говорит ровно то,
 *  что нужно: пересними.
 *
 *  Зачем поля. Без внешних отступов раскладку детей нельзя
 *  предсказать — измерено на живой странице, расхождение в сотни
 *  пикселей. Без отдельного `grid` сетка сводилась к колонке, и
 *  предсказание шло по неверной оси; это была главная причина отказов
 *  от auto-layout. */
export const IR_VERSION = 3
export type IrVersion = typeof IR_VERSION

/** Сырой конверт: читается ДО валидации, чтобы отличить «это не наш файл»
 *  от «наш файл чужой версии» и дать внятное сообщение вместо простыни zod.
 *  Бандл — односверсионный артефакт: миграций нет, есть отказ. */
export type BundleEnvelope = { format?: unknown; version?: unknown }
